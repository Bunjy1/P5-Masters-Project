
from pathlib import Path

import h5py
import numpy as np
import torch
from tqdm import tqdm

from pytomography.io.SPECT import dicom


def _load_projections(filename):
    """Load projections with angular dimension first."""
    projections = dicom.get_projections(str(filename), index_peak=0)

    if isinstance(projections, torch.Tensor):
        projections = projections.detach().cpu().numpy()

    projections = np.asarray(projections).squeeze()

    if projections.ndim != 3:
        raise ValueError(
            f"Expected projections with shape (angles, rows, cols), "
            f"but got {projections.shape}"
        )

    projections = projections.astype(np.float32)

    if not np.all(np.isfinite(projections)):
        raise ValueError("Projections contain NaN or infinite values")

    if np.any(projections < 0):
        raise ValueError("Projections contain negative counts")

    return projections


def _noise_group_name(fraction):
    """Convert a fraction to a consistent HDF5 group name."""
    return f"fraction_{fraction:.4f}".replace(".", "p")


def create_hdf5_dataset(
    topdirs,
    output_file="spect_dataset.h5",
    max_scans=None,
    noise_fractions=(1.0, 0.5, 0.25, 0.1),
    seed=12345,
    expected_shape=(128, 128),
):
    """
    Store clean projections once per scan and precompute noisy versions.

    Failed files are skipped and reported.

    Assumes projections have shape (angles, rows, cols).
    Noise is generated by binomial thinning of rounded counts.
    """

    noise_fractions = tuple(float(f) for f in noise_fractions)

    if not noise_fractions:
        raise ValueError("Provide at least one noise fraction.")

    if any(not 0 < f <= 1 for f in noise_fractions):
        raise ValueError(
            "Noise fractions must be in the interval (0, 1]."
        )

    if len(set(noise_fractions)) != len(noise_fractions):
        raise ValueError("Noise fractions must be unique.")

    files = sorted(
        path
        for topdir in topdirs
        for path in Path(topdir).rglob("*")
        if path.is_file() and path.suffix.lower() == ".dcm"
    )

    if not files:
        raise FileNotFoundError("No .dcm files found in topdirs.")

    output_file = str(output_file)
    skipped_files = []
    n_saved = 0

    with h5py.File(output_file, "w") as h5:
        h5.attrs["noise_fractions"] = noise_fractions
        h5.attrs["seed"] = seed
        h5.attrs["description"] = (
            "Clean projections and precomputed binomially thinned versions"
        )

        clean_root = h5.create_group("scans")
        noisy_root = h5.create_group("noisy")

        for fraction in noise_fractions:
            noisy_root.create_group(_noise_group_name(fraction))

        for filename in tqdm(files, desc="Creating dataset"):
            if max_scans is not None and n_saved >= max_scans:
                break
            # Load and validate before creating any HDF5 entries.
            try:
                projections = _load_projections(filename)

                if expected_shape is not None:
                  if projections.shape[1:] != expected_shape:
                      print(
                          f"\nSkipping: {filename}\n"
                          f"  Reason: projection shape {projections.shape[1:]} "
                          f"does not match {expected_shape}"
                      )
                      skipped_files.append(
                          (str(filename), f"Unexpected shape: {projections.shape[1:]}")
                      )
                      continue

            except Exception as e:
                print(f"\nSkipping: {filename}")
                print(f"  Reason: {type(e).__name__}: {e}")
                skipped_files.append((str(filename), str(e)))
                continue

            n_angles = projections.shape[0]

            # Binomial sampling requires non-negative integer counts.
            counts = np.rint(projections)

            # Use int64 for binomial sampling.
            counts = counts.astype(np.int64)

            # Assign IDs only to successfully loaded scans.
            scan_id = f"scan_{n_saved:05d}"

            try:
                # Store clean projections once.
                clean_group = clean_root.create_group(scan_id)
                clean_group.attrs["source_file"] = str(filename)
                clean_group.attrs["n_angles"] = n_angles

                clean_group.create_dataset(
                    "projections",
                    data=projections,
                    chunks=(1, *projections.shape[1:]),
                    compression="gzip",
                    shuffle=True,
                )

                # Save one noisy projection stack per noise level.
                for fraction_idx, fraction in enumerate(noise_fractions):
                    rng = np.random.default_rng(
                        np.random.SeedSequence(
                            [seed, n_saved, fraction_idx]
                        )
                    )

                    if fraction == 1.0:
                        noisy_projections = projections.copy()
                    else:
                        noisy_projections = rng.binomial(
                            counts, fraction
                        ).astype(np.float32)

                    group = noisy_root[_noise_group_name(fraction)]

                    group.create_dataset(
                        scan_id,
                        data=noisy_projections,
                        chunks=(1, *projections.shape[1:]),
                        compression="gzip",
                        shuffle=True,
                    )

                n_saved += 1

            except Exception:
                # A write failure is not a bad input file. Stop rather
                # than silently leaving a partially written scan.
                raise

    print(f"\nDataset saved to: {output_file}")
    print(f"Files found: {len(files)}")
    print(f"Successfully saved: {n_saved}")
    print(f"Skipped: {len(skipped_files)}")
    print(f"Noise fractions: {noise_fractions}")

    if skipped_files:
        print("\nSkipped files:")
        for filename, reason in skipped_files:
            print(f"  {filename}")
            print(f"    {reason}")


